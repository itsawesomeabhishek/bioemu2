import torch

from bioemu2.data_interface.const import NUM_TOKENS

NUM_MSA_TOKENS: int = NUM_TOKENS


def process_msa_features(
    msa: torch.Tensor,
    deletion: torch.Tensor,
    paired: torch.Tensor,
    num_tokens_msa: int,
) -> dict[str, torch.Tensor]:
    """
    Take different MSA quantities generated by preprocessing and featurize for the sequence
    embedder.

    Args:
        msa: Basic MSA features with shape [num_features_msa x num_tokens].
        deletion: Deletion mask with shape [num_features_msa x num_tokens].
        paired: Paired MSA features generated as described in the Boltz-1 publication
          (shape [num_features_msa x num_tokens]).
        num_tokens_msa: Number of one-hot tokens used to featurize MSA.

    Returns:
        Dictionary with different MSA features used for example by
        the BioMoa sequence embedder. This includes the one hot encoded
        MSAs (`msa`), averaged histogram computed from the one-hot features (`profile`), paired MSA
        features (`msa_paired`, no encoding collected for convenience), deletions
        (`deletion_value`), featurized deletions (`deletion_mean`, arctan wrapper and averaging) and
        a mask for the MSA featured (`msa_mask`).
    """

    msa = torch.nn.functional.one_hot(msa, num_classes=num_tokens_msa)
    msa_mask = torch.ones_like(msa[:, :, 0])
    profile = msa.float().mean(dim=1)
    has_deletion = deletion > 0
    deletion = torch.pi / 2 * torch.arctan(deletion / 3)
    deletion_mean = deletion.mean(axis=1)

    return {
        "msa": msa,
        "msa_paired": paired,
        "deletion_value": deletion,
        "has_deletion": has_deletion,
        "deletion_mean": deletion_mean,
        "profile": profile,
        "msa_mask": msa_mask,
    }
